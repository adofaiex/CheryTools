(() => {
    const registry = window.CheryToolsSponsorRegistry;

    function byId(id) {
        return document.getElementById(id);
    }

    function renderSponsors() {
        const list = byId("sponsor-list");
        if (!list || !registry || !Array.isArray(registry.sponsors)) return;

        const enabledSponsors = registry.sponsors.filter((sponsor) => sponsor.enabled !== false);
        list.replaceChildren();
        for (const sponsor of enabledSponsors) {
            const card = document.createElement("article");
            card.className = "sponsor-card";

            const info = document.createElement("div");
            const name = document.createElement("div");
            name.className = "sponsor-name";
            name.textContent = sponsor.name;

            const uid = document.createElement("div");
            uid.className = "sponsor-uid";
            uid.textContent = `Bilibili UID · ${sponsor.uid}`;
            info.append(name, uid);

            const link = document.createElement("a");
            link.className = "sponsor-link";
            link.href = sponsor.url;
            link.target = "_blank";
            link.rel = "noopener noreferrer";
            link.textContent = "访问 Bilibili";

            card.append(info, link);
            list.appendChild(card);
        }

        const meta = byId("registry-meta");
        if (meta) {
            meta.textContent = `名单修订 ${registry.revision} · 更新于 ${registry.updatedAt}`;
        }
    }

    renderSponsors();
})();
